const STRINGS = { en: EN, ar: AR };

export function resolveLang(setting, browserLang) {
  if (setting === "en" || setting === "ar") return setting;
  return String(browserLang ?? "").toLowerCase().startsWith("ar") ? "ar" : "en";
}

export function t(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? EN[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function nameText(lang, key, fallback) {
  return (lang === "ar" && AR[key]) || fallback;
}

export function exerciseText(lang, key, field, fallback) {
  return nameText(lang, `ex.${key}.${field}`, fallback);
}

export function areaName(lang, area) {
  return nameText(lang, `area.${area}`, area);
}

export function levelName(lang, level, fallback) {
  return nameText(lang, `level.${level}`, fallback);
}

export function issueText(lang, code, fallback) {
  return nameText(lang, `issue.${code}`, fallback);
}

export function localeFor(lang) {
  return lang === "ar" ? "ar-u-nu-latn" : undefined;
}

export function translationKeys(lang) {
  return Object.keys(STRINGS[lang] ?? {});
}

export function applyLang(lang) {
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";
  for (const el of /** @type {NodeListOf<HTMLElement>} */ (document.querySelectorAll("[data-i18n]"))) el.textContent = t(lang, el.dataset.i18n);
  for (const [sel, data, attr] of [
    ["[data-i18n-placeholder]", "i18nPlaceholder", "placeholder"],
    ["[data-i18n-title]", "i18nTitle", "title"],
    ["[data-i18n-aria]", "i18nAria", "aria-label"],
  ]) {
    for (const el of /** @type {NodeListOf<HTMLElement>} */ (document.querySelectorAll(sel))) el.setAttribute(attr, t(lang, el.dataset[data]));
  }
}

/** @param {(lang: string) => void} [onChange] called with the new language when it changes */
export async function initLang(onChange = () => location.reload()) {
  const { lang } = await chrome.storage.local.get("lang");
  const resolved = resolveLang(lang, navigator.language);
  applyLang(resolved);
  chrome.storage.onChanged.addListener((changes, area) => {
    if (area === "local" && "lang" in changes) onChange(/** @type {string} */ (changes.lang.newValue));
  });
  return resolved;
}
